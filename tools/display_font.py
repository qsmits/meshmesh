"""Bake 4-bit coverage masks for the handheld UI. Run with Pillow 13.

Input: adobe-fonts/source-sans release 87b37a2daaed80fcb8e8ccb0085c4d72ddade12e.
Original OTFs and SIL OFL are in i18n/fonts/source-sans/.
"""
from pathlib import Path

from PIL import ImageFont

root = Path(__file__).resolve().parents[1]
fonts = root / "i18n/fonts/source-sans"
ranges = [(32, 126), (160, 383), (0x400, 0x45F), (0x490, 0x491),
          (0x2013, 0x2014), (0x2018, 0x2019), (0x201C, 0x201D), (0x2026, 0x2026)]
sizes = [("Caption", "Regular", 11), ("Body", "Regular", 15),
         ("Label", "Semibold", 15), ("Title", "Semibold", 22)]

with (root / "src/DisplayFontData.inc").open("w") as out:
    out.write("// Generated by tools/display_font.py. Font license: i18n/fonts/source-sans/LICENSE.md\n")
    out.write("static constexpr GlyphRange coverageRanges[] = {\n")
    index = 0
    for first, last in ranges:
        out.write(f"    {{{first}, {last}, {index}}},\n")
        index += last - first + 1
    out.write("};\n")
    for name, weight, size in sizes:
        font = ImageFont.truetype(fonts / f"SourceSans3-{weight}.otf", size)
        pixels = bytearray()
        out.write(f"static constexpr CoverageGlyph glyphs{name}[] = {{\n")
        for first, last in ranges:
            for cp in range(first, last + 1):
                c = chr(cp)
                mask, (x, y) = font.getmask2(c, mode="L", anchor="ls")
                width, height = mask.size
                advance = round(font.getlength(c))
                out.write(f"    {{{len(pixels)}, {x}, {y}, {width}, {height}, {advance}}},\n")
                alpha = [(v + 8) // 17 for v in mask]
                alpha.append(0)
                pixels.extend((a << 4) | b for a, b in zip(alpha[::2], alpha[1::2]))
        assert len(pixels) < 65536
        out.write(f"}};\nstatic constexpr uint8_t pixels{name}[] = {{\n")
        for i in range(0, len(pixels), 24):
            out.write("    " + ", ".join(map(str, pixels[i:i + 24])) + ",\n")
        out.write("};\n")
        out.write(f"static constexpr CoverageFace face{name} = {{glyphs{name}, pixels{name}}};\n")
